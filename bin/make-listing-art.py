#!/usr/bin/env python3
"""Original GPL-2.0-or-later WordPress directory art, using Pillow for rendering."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'wordpress-assets'
OUT.mkdir(exist_ok=True)
NAVY, CYAN, WHITE, MUTED = '#102639', '#55dfce', '#ffffff', '#bdd2df'
FONT = '/System/Library/Fonts/Supplemental/Arial.ttf'
BOLD = '/System/Library/Fonts/Supplemental/Arial Bold.ttf'


def font(size, bold=False):
    return ImageFont.truetype(BOLD if bold else FONT, size)


def mark(draw, x, y, size):
    unit = size / 256
    def box(a, b, c, d): return (x+a*unit, y+b*unit, x+c*unit, y+d*unit)
    draw.rounded_rectangle(box(28, 45, 228, 224), radius=24*unit, fill=WHITE)
    draw.rounded_rectangle(box(28, 45, 228, 108), radius=24*unit, fill=CYAN)
    draw.rectangle(box(28, 84, 228, 108), fill=CYAN)
    for xx in (79, 177):
        draw.line((x+xx*unit, y+27*unit, x+xx*unit, y+67*unit), fill=WHITE, width=round(15*unit))
    draw.line((x+80*unit, y+161*unit, x+114*unit, y+191*unit, x+177*unit, y+136*unit), fill=NAVY, width=max(1, round(16*unit)), joint='curve')


icon = Image.new('RGB', (256, 256), NAVY)
mark(ImageDraw.Draw(icon), 0, 0, 256)
icon.save(OUT/'icon-256x256.png')
icon.resize((128, 128), Image.Resampling.LANCZOS).save(OUT/'icon-128x128.png')
banner = Image.new('RGB', (1544, 500), NAVY)
draw = ImageDraw.Draw(banner)
mark(draw, 88, 82, 290)
draw.text((438, 91), 'SaveTheDate', font=font(86, True), fill=WHITE)
draw.text((441, 207), 'Calendar links for Gravity Forms', font=font(38), fill=CYAN)
draw.text((441, 285), 'Google  /  Outlook  /  Microsoft 365  /  Yahoo  /  .ics', font=font(25), fill=MUTED)
draw.text((441, 407), 'KELEX LABS', font=font(22, True), fill=MUTED)
banner.save(OUT/'banner-1544x500.png')
banner.resize((772, 250), Image.Resampling.LANCZOS).save(OUT/'banner-772x250.png')
(OUT/'README.md').write_text('''# WordPress directory assets\n\nOriginal artwork by Kelex Labs, GPL-2.0-or-later. Generated by `bin/make-listing-art.py` with Pillow and system Arial rendering; no font files are bundled. No provider logos or Gravity Forms logo are used.\n\nBanners and icons belong in WordPress SVN `/assets`, outside the installable ZIP. Screenshots must be captured from the actual playground UI before submission; none are fabricated here.\n''')
print('Created directory banners and icons in ' + str(OUT))
